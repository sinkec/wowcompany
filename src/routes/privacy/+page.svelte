			<b>When you sign in with Google:</b> your name, email address and profile picture, as provided by Google. That's
			it — we don't get your password, contacts, files or anything else.
		</li>
		<li>
			<b>When you petition to join:</b> the World of Warcraft character name you type in, and the time you sent it.
		</li>
		<li>
			<b>About tracked characters:</b> public character data from the official Battle.net API (level, gear, statistics,
			talents, professions and similar), plus a history of how those numbers change.
		</li>
	</ul>

	<h2 class="text-xl font-semibold">What we do with it</h2>
	<ul class="list-disc space-y-1 pl-6">
		<li>Show character stats, leaderboards and progress on this website.</li>
		<li>Post session summaries and answer slash commands in our private Discord server.</li>
		<li>Let the site admin decide who is a member and what is visible to the public.</li>
	</ul>
	<p>No ads, no analytics trackers, no selling or sharing data with anyone for marketing.</p>

